#!/usr/bin/env python3
"""BEAST2 XML generator for stochastic SIR trajectory simulations.

This module generates BEAST2 XML configuration files for simulating stochastic
SIR (Susceptible-Infected-Recovered) epidemic trajectories with spatial structure.
It supports multiple demes (subpopulations) with configurable mixing patterns
and epidemiological parameters. Rates are given in per year units.
"""

import argparse
import logging
import os
from typing import Dict, List, Optional, Tuple, Union

from xml.etree import ElementTree as ET
from xml.etree.ElementTree import Element, Comment
import numpy as np
import pandas as pd

logger = logging.getLogger(__name__)

# Default parameter values
DEFAULT_KAPPA = 2.0
DEFAULT_FREQ_PARAMETER = [0.25, 0.25, 0.25, 0.25]
DEFAULT_SEQUENCE_LENGTH = 1000
DEFAULT_RANDOM_SEED = 42


def create_beast_xml_element(
    name: str, attrib: Optional[Dict] = None, text: Optional[str] = None
) -> Element:
    """Helper function to create an XML element with optional attributes and text."""
    element = Element(name)
    if attrib:
        for key, value in attrib.items():
            element.set(key, str(value))
    if text is not None:
        element.text = str(text)
    return element


def create_birthdeath_xml(
    output_file: str,
    reactions: list,
    populations: dict,
    mutation_rate: float,
    nsims: int = 10,
    maxTime: int = 0.5,
    endsWhen: int = 200,
    kappa: float = 2.0,
    freq_parameter: Optional[list] = None,
) -> None:
    """
    Create a BEAST2 XML file for stochastic SIR trajectory simulation.

    Args:
        output_file (str): Path to save the XML file
        R0 (float): Basic reproductive number
        samplingrate (float): Sampling rate
        beta (float, optional): Transmission rate
        gamma (float, optional): Recovery rate

    Raises:
        ValueError: If neither beta nor gamma is provided, or if both are provided
    """

    # Create the root element
    root = Element("beast")
    root.set("version", "2.0")
    root.set(
        "namespace", "beast.base.inference.parameter:beast.base.inference:remaster"
    )

    # Add comments
    root.append(Comment(" Stochastic SIR trajectory simulation. "))
    root.append(Comment("Generated by create_birthdeath_simXML.py"))

    # Add kappa and freqParameter as user-supplied parameters
    param_kappa = create_beast_xml_element(
        "parameter",
        {"id": "kappa.s", "spec": "parameter.RealParameter", "name": "stateNode"},
        text=str(kappa),
    )
    root.append(param_kappa)

    freq_values = (
        freq_parameter if freq_parameter is not None else [0.25, 0.25, 0.25, 0.25]
    )
    param_freq = create_beast_xml_element(
        "parameter",
        {
            "id": "freqParameter.s",
            "spec": "parameter.RealParameter",
            "name": "stateNode",
            "dimension": "4",
        },
        text=" ".join(str(x) for x in freq_values),
    )
    root.append(param_freq)

    # Add sequence simulation block
    run_seq = create_beast_xml_element(
        "run", {"spec": "Simulator", "nSims": str(nsims)}
    )
    root.append(run_seq)

    simulate_seq = create_beast_xml_element(
        "simulate",
        {
            "spec": "feast.simulation.SimulatedAlignment",
            "outputFileName": "$(filebase).nexus",
            "sequenceLength": DEFAULT_SEQUENCE_LENGTH,
        },
    )
    run_seq.append(simulate_seq)

    site_model = create_beast_xml_element(
        "siteModel",
        {
            "spec": "beast.base.evolution.sitemodel.SiteModel",
            "mutationRate": mutation_rate,
        },
    )
    simulate_seq.append(site_model)

    subst_model = create_beast_xml_element(
        "substModel",
        {"spec": "beast.base.evolution.substitutionmodel.HKY", "kappa": "@kappa.s"},
    )
    site_model.append(subst_model)
    # Add frequencies to substitution model
    freqs = create_beast_xml_element(
        "frequencies",
        {
            "spec": "beast.base.evolution.substitutionmodel.Frequencies",
            "frequencies": "@freqParameter.s",
        },
    )
    subst_model.append(freqs)

    # Add tree and trajectory
    tree = create_beast_xml_element("tree", {"spec": "SimulatedTree", "id": "tree"})
    simulate_seq.append(tree)

    trajectory = create_beast_xml_element(
        "trajectory", {"spec": "StochasticTrajectory"}
    )
    tree.append(trajectory)
    # Set trajectory attributes
    trajectory.set("id", "SIRTrajectory")
    trajectory.set("maxTime", f"{maxTime}")
    if endsWhen is not None:
        trajectory.set("endsWhen", f"sample>={endsWhen}")

    # Populations for sequence simulation
    for pop_id, (pop_name, pop_value) in populations.items():
        pop = create_beast_xml_element(
            pop_name, {"spec": "RealParameter", "id": pop_id, "value": pop_value}
        )
        trajectory.append(pop)
    # Add reactions to trajectory
    for reaction in reactions:
        if reaction["changeTimes"] is not None:
            reaction_element = create_beast_xml_element(
                "reaction",
                {
                    "spec": "Reaction",
                    "rate": reaction["rate"],
                    "changeTimes": reaction["changeTimes"],
                },
                text=reaction["reaction_text"],
            )
        else:
            reaction_element = create_beast_xml_element(
                "reaction",
                {"spec": "Reaction", "rate": reaction["rate"]},
                text=reaction["reaction_text"],
            )
        trajectory.append(reaction_element)

    # Sequence simulation loggers
    logger_traj = create_beast_xml_element(
        "logger", {"spec": "Logger", "fileName": "$(filebase).traj"}
    )
    run_seq.append(logger_traj)

    log_traj = create_beast_xml_element("log", {"idref": "SIRTrajectory"})
    logger_traj.append(log_traj)
    # Add tree logger
    logger_trees = create_beast_xml_element(
        "logger", {"id": "Logger", "fileName": "$(filebase).trees", "mode": "tree"}
    )
    run_seq.append(logger_trees)

    # Add log for tree
    log_trees = create_beast_xml_element(
        "log", {"spec": "TypedTreeLogger", "tree": "@tree"}
    )
    logger_trees.append(log_trees)

    # Add stats logger
    logger_stats = create_beast_xml_element("logger", {"spec": "Logger"})
    run_seq.append(logger_stats)

    # Add stats log
    log_stats = create_beast_xml_element(
        "log", {"spec": "beast.base.evolution.tree.TreeStatLogger", "tree": "@tree"}
    )
    logger_stats.append(log_stats)

    # Write the XML to file with proper formatting
    def indent(elem, level=0):
        """Helper function to properly indent the XML output."""
        i = "\n" + level * "  "
        if len(elem):
            if not elem.text or not elem.text.strip():
                elem.text = i + "  "
            if not elem.tail or not elem.tail.strip():
                elem.tail = i
            for elem in elem:
                indent(elem, level + 1)
            if not elem.tail or not elem.tail.strip():
                elem.tail = i
        else:
            if level and (not elem.tail or not elem.tail.strip()):
                elem.tail = i

    # Indent the XML tree
    indent(root)

    # Create the XML declaration
    xml_declaration = '<?xml version="1.0" encoding="UTF-8" standalone="no"?>\n'
    # Convert to string and add XML declaration
    xml_str = ET.tostring(root, encoding="unicode")

    # Write to file
    with open(output_file, "w", encoding="utf-8") as f:
        f.write(xml_declaration)
        f.write(xml_str)


def randomly_assign_beta(
    min_beta: float, sum_beta: float, n: int, rng: np.random.Generator
) -> np.ndarray:
    """Randomly assign beta values between specified bounds.

    This function generates n random values that sum to sum_beta, with each value
    being at least min_beta. The values are randomly shuffled before returning.

    Args:
        min_beta: Minimum value for any single beta.
        sum_beta: Total sum that all beta values must equal.
        n: Number of beta values to generate.
        rng: Random number generator instance.

    Returns:
        Array of n beta values that sum to sum_beta.

    Raises:
        ValueError: If min_beta * n > sum_beta.
    """
    if min_beta * n > sum_beta:
        raise ValueError(
            f"Cannot assign {n} values each >= {min_beta} to sum to {sum_beta}"
        )

    # Generate n-1 random points between min_beta and sum_beta
    points = rng.uniform(min_beta, sum_beta, n - 1)
    points = np.sort(points)

    # Calculate differences between points to get n values that sum to sum_beta
    values = np.zeros(n)
    values[0] = points[0]
    values[1:-1] = points[1:] - points[:-1]
    values[-1] = sum_beta - points[-1]

    # Shuffle to randomize the order
    rng.shuffle(values)
    return values


def get_beta_from_R_direct(
    ndemes: int,
    R0_star: np.ndarray,
    offdiag_R: np.ndarray,
    gamma: Union[float, np.ndarray],
) -> List[np.ndarray]:
    """Calculate transmission rates directly from R values without using a mixing matrix.

    This function computes the transmission rate matrix (beta_ij) between demes based on:
    1. The basic reproduction number (R0) for each time period (used for within-deme rates)
    2. The off-diagonal R value (offdiag_R, constant across time, used for between-deme rates)
    3. The recovery rate (gamma)
    For within-deme: beta_ii = R0 * gamma (varies by time period)
    For between-deme: beta_ij = offdiag_R * gamma (constant across time)

    Args:
        ndemes: Number of demes (subpopulations).
        R0_star: Basic reproduction number for each time period (used for within-deme rates).
        offdiag_R: Off-diagonal R value (constant, used for between-deme rates).
        gamma: Recovery rate(s). If scalar, same for all demes.

    Returns:
        List of transmission rate matrices (beta_ij) for each time period where beta_ij is the transmission
        rate from deme j to deme i.

    Raises:
        ValueError: If input shapes are inconsistent or parameters are invalid.
    """
    if any(R0_star <= 0):
        raise ValueError("R0_star must be positive")
    if np.any(offdiag_R <= 0):
        raise ValueError("offdiag_R must be positive")
    if ndemes <= 0:
        raise ValueError("Number of demes must be positive")

    # Initialize empty list to store beta matrices for each time period
    beta_matrices = []

    # Convert gamma to scalar if it's an array (should be same for all demes)
    gamma_val = float(gamma) if np.isscalar(gamma) else float(gamma[0])

    # Create beta matrices for each time period
    for t in range(R0_star.shape[0]):
        beta = np.zeros((ndemes, ndemes))

        # Within-deme rates: beta_ii = R0[t] * gamma
        for i in range(ndemes):
            beta[i, i] = R0_star[t] * gamma_val

        # Between-deme rates: beta_ij = offdiag_R * gamma (constant across time)
        for i in range(ndemes):
            for j in range(ndemes):
                if i != j:
                    beta[i, j] = offdiag_R[i, j] * gamma_val

        beta_matrices.append(beta)

    return beta_matrices


def get_beta_demes(
    ndemes: int,
    R0_star: np.ndarray,
    gamma: Union[float, np.ndarray],
    population_sizes: np.ndarray,
    mixing_matrix: np.ndarray,
    seed: int = DEFAULT_RANDOM_SEED,
) -> np.ndarray:
    """Calculate transmission rates between demes using the spectral radius method for each time period.

    This function computes the transmission rate matrix (beta_ij) between demes based on:
    1. The target basic reproduction number (R0*)
    2. The recovery rate (gamma)
    3. Population sizes
    4. A mixing matrix

    The method ensures that the spectral radius of the next generation matrix
    equals the target R0 value.

    Args:
        ndemes: Number of demes (subpopulations).
        R0_star: Target basic reproduction number for each time period.
        gamma: Recovery rate(s). If scalar, same for all demes.
        population_sizes: Array of population sizes for each deme.
        mixing_matrix: Relative mixing matrix between demes (ndemes x ndemes).
        seed: Random seed for reproducibility. Defaults to 42.

    Returns:
        ndarray: Transmission rate matrix (beta_ij) for each time period where beta_ij is the transmission
                rate from deme j to deme i.

    Raises:
        ValueError: If input shapes are inconsistent or parameters are invalid.
    """
    if any(R0_star <= 0):
        raise ValueError("R0_star must be positive")
    if ndemes <= 0:
        raise ValueError("Number of demes must be positive")
    if mixing_matrix.shape != (ndemes, ndemes):
        raise ValueError(
            f"Mixing matrix must be {ndemes}x{ndemes}, got {mixing_matrix.shape}"
        )

    # Initialize empty list to store beta matrices for each time period
    beta_matrices = []

    rng = np.random.default_rng(seed)

    # Convert gamma to array if it's a scalar
    gamma_arr = np.full(ndemes, gamma) if np.isscalar(gamma) else np.asarray(gamma)

    # Normalize population sizes to get fractions
    f = np.asarray(population_sizes, dtype=float)
    if np.any(f <= 0):
        raise ValueError("All population sizes must be positive")
    f = f / f.sum()

    # Compute dominant eigenvalue of unscaled next generation matrix K_0
    K0 = mixing_matrix @ np.diag(f) @ np.diag(1.0 / gamma_arr)

    # Compute spectral radius (dominant eigenvalue) of K0
    eigenvalues = np.linalg.eigvals(K0)
    rho0 = np.max(np.abs(eigenvalues))

    for i in range(R0_star.shape[0]):
        # Compute scaling factor for each time period
        scale_factor = R0_star[i] / rho0
        # Scale the transmission rates for each time period
        beta_matrices.append(scale_factor * mixing_matrix)

    return beta_matrices


def create_transmission_reactions(
    beta_matrices: np.ndarray,
    change_times: List[float],
    population_sizes: np.ndarray,
    gamma: float,
    sampling_rate: float,
    time_varying_interdeme_R0: bool = False,
) -> List[Dict]:
    """
    Create XML string for transmission reactions with time-varying rates.

    Args:
        beta_matrices: List of transmission rate matrices for each time period.
        change_times: List of time points where the transmission rates change.
        population_sizes: Array of population sizes for each deme.
        gamma: Recovery rate.
        sampling_rate: Sampling rate for the SIR model.
        time_varying_interdeme_R0: Whether to use time-varying interdeme R0 values.
    Returns:
        XML string containing all reactions
    """
    reactions = []

    # Within-population reactions
    for i in range(len(population_sizes)):
        reaction = {}
        if len(beta_matrices) > 1 and change_times is not None:
            rate_values = [
                str(beta_matrices[step][i, i] / population_sizes[i])
                for step in range(len(beta_matrices))
            ]
            rate_string = " ".join(rate_values)
            change_times_string = " ".join([str(time) for time in change_times])
            reaction["rate"] = rate_string
            reaction["changeTimes"] = change_times_string
        else:
            rate_values = [str(beta_matrices[0][i, i] / population_sizes[i])]
            rate_string = " ".join(rate_values)
            reaction["rate"] = rate_string
            reaction["changeTimes"] = None
        reaction["reaction_text"] = f"S[{i}] + I[{i}] -> 2I[{i}] + NewInfectCount[{i}]"

        reactions.append(reaction)

        reaction = {}
        reaction["rate"] = str(gamma * sampling_rate)
        reaction["changeTimes"] = None
        reaction["reaction_text"] = f"I[{i}] -> sample"
        reactions.append(reaction)

        reaction = {}
        reaction["rate"] = str(gamma * (1 - sampling_rate))
        reaction["changeTimes"] = None
        reaction["reaction_text"] = f"I[{i}] -> Rh[{i}]"
        reactions.append(reaction)

    # Between-population reactions
    for i in range(len(population_sizes)):
        for j in range(len(population_sizes)):
            if i != j:
                reaction = {}
                if (
                    time_varying_interdeme_R0
                    and len(beta_matrices) > 1
                    and change_times is not None
                ):
                    rate_values = [
                        str(beta_matrices[step][i, j] / population_sizes[j])
                        for step in range(len(beta_matrices))
                    ]
                    rate_string = " ".join(rate_values)
                    change_times_string = " ".join([str(time) for time in change_times])
                    reaction["rate"] = rate_string
                    reaction["changeTimes"] = change_times_string
                else:
                    rate_values = [str(beta_matrices[0][i, j] / population_sizes[j])]
                    rate_string = " ".join(rate_values)
                    reaction["rate"] = rate_string
                    reaction["changeTimes"] = None
                reaction["reaction_text"] = (
                    f"I[{i}] + S[{j}] -> I[{i}] + I[{j}] + NewInfectCount[{j}]"
                )
                reactions.append(reaction)

    return reactions


def create_reaction_list(
    ndemes: int, params: Dict[str, float]
) -> List[Tuple[str, str]]:
    """Create the list of reactions for the SIR model.

    Args:
        ndemes: Number of demes.
        params: Dictionary of parameter values.

    Returns:
        List of (reaction, rate) tuples.
    """
    reactions = []

    # Within-population reactions
    for i in range(ndemes):
        # Infection: S + I -> 2I
        reactions.append((f"S[{i}] + I[{i}] -> 2I[{i}]", f"@betareaction{i}"))

        # Recovery: I -> R (sampled)
        reactions.append((f"I[{i}] -> sample", f"@gammasample{i}"))

        # Recovery: I -> Rh (hidden)
        reactions.append((f"I[{i}] -> Rh[{i}]", f"@gammahidden{i}"))

    # Between-population infections
    for i in range(ndemes):
        for j in range(ndemes):
            if i != j and f"infect{i}{j}" in params:
                reactions.append(
                    (f"I[{i}] + S[{j}] -> I[{i}] + I[{j}]", f"@infect{i}{j}")
                )

    return reactions


def parse_arguments() -> argparse.Namespace:
    """Parse command line arguments for the BEAST2 XML generator.

    Returns:
        Parsed command line arguments.
    """
    parser = argparse.ArgumentParser(
        description="Create BEAST2 XML configuration for stochastic SIR trajectory simulation."
    )

    # I/O parameters
    io_group = parser.add_argument_group("Input/Output")
    io_group.add_argument(
        "--output_file",
        type=str,
        default="SIR_simulation.xml",
        help="Output XML file name",
    )
    io_group.add_argument(
        "--params_csv",
        type=str,
        default=None,
        help=(
            "Optional path to write a CSV summary of parameters. "
            "If not provided, a file named '<output_file_basename>_parameters.csv' will be written."
        ),
    )
    io_group.add_argument(
        "--nsims",
        type=int,
        default=1,
        help="Number of simulations (must be 1 when generating alignments)",
    )

    io_group.add_argument(
        "--maxTime", type=float, default=0.5, help="End time for the simulation"
    )
    io_group.add_argument(
        "--endsWhen",
        type=int,
        default=1000,
        help="Maximum number of samples for the simulation",
    )

    # Population parameters
    pop_group = parser.add_argument_group("Population Structure")
    pop_group.add_argument(
        "--ndemes", type=int, default=6, help="Number of demes (subpopulations)"
    )

    # Sequence evolution parameters
    seq_group = parser.add_argument_group("Sequence Evolution")
    seq_group.add_argument(
        "--kappa",
        type=float,
        default=DEFAULT_KAPPA,
        help=f"Kappa parameter for HKY model [default: {DEFAULT_KAPPA}]",
    )
    seq_group.add_argument(
        "--freqParameter",
        type=str,
        default=" ".join(str(f) for f in DEFAULT_FREQ_PARAMETER),
        help="Base frequencies for HKY model (space-separated, default: 0.25 0.25 0.25 0.25)",
    )

    # Mixing/contact matrix parameters (mutually exclusive, required only if usematrix is True)
    mixing_group = parser.add_mutually_exclusive_group(required=False)
    mixing_group.add_argument(
        "--mixing_matrix",
        type=str,
        help="Path to CSV file containing the mixing matrix M (n x n matrix)",
    )
    mixing_group.add_argument(
        "--contact_matrix",
        type=str,
        help="Path to CSV file containing the contact matrix C (n x n matrix). Will calculate M = q*C. q to be provided in sampled_params",
    )

    # Sampled parameter input (required)
    sampled_group = parser.add_argument_group("Sampled Parameters")
    sampled_group.add_argument(
        "--sampled_params",
        type=str,
        required=True,
        help="Path to CSV with sampled parameters (columns: parameter, deme, value)",
    )
    sampled_group.add_argument(
        "--usematrix",
        action="store_true",
        help="Use the passed contact or mixing matrix (default: True if matrix provided, False otherwise)",
    )

    args = parser.parse_args()

    # Validate mutual dependencies
    if args.usematrix:
        if args.mixing_matrix is None and args.contact_matrix is None:
            parser.error(
                "--usematrix requires either --mixing_matrix or --contact_matrix"
            )
        if args.contact_matrix is not None and args.sampled_params is None:
            parser.error("--contact_matrix requires --sampled_params")
    else:
        logger.info(
            "Using R values in params file directly with offdiag_R parameter to calculate transmission rates."
        )

    return args


def load_population_vectors(
    s_str: str, i_str: str, ndemes: int
) -> Tuple[np.ndarray, np.ndarray]:
    """Parse and validate population vectors from input strings.

    Args:
        s_str: Space-separated string of susceptible counts.
        i_str: Space-separated string of infectious counts.
        ndemes: Expected number of demes.

    Returns:
        Tuple of (S_list, I_list) numpy arrays.

    Raises:
        ValueError: If input lengths don't match ndemes.
    """
    try:
        S_list = np.array([int(x) for x in s_str.strip().split()])
        I_list = np.array([int(x) for x in i_str.strip().split()])

        if len(S_list) != ndemes or len(I_list) != ndemes:
            raise ValueError(
                f"Population vectors must have length {ndemes}. "
                f"Got S={len(S_list)}, I={len(I_list)}"
            )

        if np.any(S_list < 0) or np.any(I_list < 0):
            raise ValueError("Population counts cannot be negative")

        return S_list, I_list

    except ValueError as e:
        raise ValueError(f"Invalid population vector format: {str(e)}")


def load_mixing_matrix(
    mixing_matrix_path: Optional[str],
    contact_matrix_path: Optional[str],
    per_contact_prob: Optional[float],
    ndemes: int,
) -> np.ndarray:
    """Load and validate the mixing matrix from either direct input or contact matrix.

    Args:
        mixing_matrix_path: Path to CSV file with mixing matrix.
        contact_matrix_path: Path to CSV file with contact matrix.
        per_contact_prob: Per-contact transmission probability.
        ndemes: Expected matrix dimensions (ndemes x ndemes).

    Returns:
        The mixing matrix as a numpy array.

    Raises:
        FileNotFoundError: If input files don't exist.
        ValueError: If matrix dimensions are incorrect.
    """
    if mixing_matrix_path:
        if not os.path.exists(mixing_matrix_path):
            raise FileNotFoundError(
                f"Mixing matrix file not found: {mixing_matrix_path}"
            )
        M = pd.read_csv(mixing_matrix_path, header=None).values
    else:
        if not os.path.exists(contact_matrix_path):
            raise FileNotFoundError(
                f"Contact matrix file not found: {contact_matrix_path}"
            )
        C = pd.read_csv(contact_matrix_path, header=None).values
        M = per_contact_prob * C

    if M.shape != (ndemes, ndemes):
        raise ValueError(
            f"Matrix must be {ndemes}x{ndemes}, got {M.shape[0]}x{M.shape[1]}"
        )

    if np.any(M < 0):
        raise ValueError("Matrix cannot contain negative values")

    # Note: When using a contact matrix C, the mixing matrix is M = q * C.
    # The next-generation matrix K_0 = M @ diag(f) @ diag(1/gamma) is then
    # scaled so that its spectral radius equals R0 (see get_beta_demes).
    # This means M encodes *relative* mixing intensities, and the absolute
    # transmission level is set by the R0 calibration — so the choice of q
    # only changes the relative weight of between- vs within-deme transmission,
    # not the overall epidemic growth rate.

    return M


def _get_scalar(df: pd.DataFrame, param_name: str) -> float:
    """Fetch a global (deme-independent) scalar parameter from the sampled params."""
    sub = df[(df["parameter"] == param_name) & (df["deme"].isna())]
    if sub.empty:
        raise ValueError(
            f"Missing global parameter '{param_name}' in sampled_params"
        )
    return float(sub.iloc[0]["value"])


def _get_vector(df: pd.DataFrame, param_name: str, ndemes: int) -> np.ndarray:
    """Fetch a per-deme vector parameter from the sampled params."""
    sub = df[df["parameter"] == param_name]
    sub = sub[sub["deme"].notna()].copy()
    sub["deme"] = sub["deme"].astype(int)
    vals = np.full(ndemes, np.nan, dtype=float)
    for _, row in sub.iterrows():
        d = int(row["deme"])
        if 0 <= d < ndemes:
            vals[d] = float(row["value"])
    if np.any(np.isnan(vals)):
        raise ValueError(
            f"Missing values for per-deme parameter '{param_name}' in sampled_params"
        )
    return vals


def _get_matrix(df: pd.DataFrame, param_name: str, ndemes: int) -> np.ndarray:
    """Fetch a deme-pair matrix parameter from the sampled params.

    Deme pairs are encoded as ``"i_j"`` in the ``deme`` column.
    """
    sub = df[df["parameter"] == param_name]
    sub = sub[sub["deme"].notna()].copy()
    vals = np.full((ndemes, ndemes), np.nan, dtype=float)
    for _, row in sub.iterrows():
        direction = row["deme"].split("_")
        d1 = int(direction[0])
        d2 = int(direction[1])
        if 0 <= d1 < ndemes and 0 <= d2 < ndemes:
            vals[d1, d2] = float(row["value"])
        else:
            raise ValueError(f"Invalid deme indices: {d1}, {d2}")
    return vals


def load_inputs(
    args: argparse.Namespace,
) -> Tuple[pd.DataFrame, Dict]:
    """Load and validate the sampled-parameters CSV.

    Returns:
        Tuple of (df_sampled, params) where *params* is a dict with keys:
        S_list, I_list, population_sizes, gamma, samplingrate, mutation_rate,
        q, R0_val, change_times.
    """
    df_sampled = pd.read_csv(args.sampled_params)
    if not {"parameter", "deme", "value"}.issubset(df_sampled.columns):
        raise ValueError(
            "sampled_params CSV must have columns: parameter, deme, value"
        )

    # Sanity-check deme count
    per_deme = df_sampled[df_sampled["deme"].notna()]
    demes = sorted(int(d) for d in per_deme["deme"].dropna().unique())
    if len(demes) != args.ndemes:
        print(
            "Warning: ndemes from CLI does not match demes in sampled_params; "
            "using CLI ndemes for sizing."
        )

    params: Dict = {}
    params["S_list"] = _get_vector(df_sampled, "S", args.ndemes).astype(int)
    params["I_list"] = _get_vector(df_sampled, "I", args.ndemes).astype(int)
    params["population_sizes"] = _get_vector(
        df_sampled, "population_size", args.ndemes
    ).astype(int)
    params["gamma"] = _get_scalar(df_sampled, "gamma")
    params["samplingrate"] = _get_scalar(df_sampled, "samplingrate")
    params["mutation_rate"] = _get_scalar(df_sampled, "mutation_rate")
    params["q"] = (
        _get_scalar(df_sampled, "q")
        if (df_sampled["parameter"] == "q").any()
        else None
    )

    # R0 values for each time period (sorted by parameter name, e.g. R0_0, R0_1, …)
    R0_rows = df_sampled[
        df_sampled["parameter"].str.startswith("R0_")
    ].sort_values(by="parameter")
    params["R0_val"] = R0_rows["value"].astype(float).values
    params["change_times"] = np.linspace(
        0, args.maxTime, params["R0_val"].shape[0] + 1
    )[1:-1]

    return df_sampled, params


def compute_betas(
    args: argparse.Namespace,
    df_sampled: pd.DataFrame,
    params: Dict,
) -> Tuple[List[np.ndarray], Optional[np.ndarray], bool]:
    """Compute transmission-rate matrices and reaction list.

    Returns:
        Tuple of (beta_matrices, offdiag_R, time_varying_interdeme_R0).
        *offdiag_R* is ``None`` when using a mixing matrix.
    """
    if args.usematrix:
        M = load_mixing_matrix(
            args.mixing_matrix, args.contact_matrix, params["q"], args.ndemes
        )
        beta_matrices = get_beta_demes(
            ndemes=args.ndemes,
            R0_star=params["R0_val"],
            gamma=params["gamma"],
            population_sizes=params["population_sizes"],
            mixing_matrix=M,
            seed=DEFAULT_RANDOM_SEED,
        )
        return beta_matrices, None, True

    offdiag_R = _get_matrix(df_sampled, "offdiag_R", args.ndemes)
    beta_matrices = get_beta_from_R_direct(
        ndemes=args.ndemes,
        R0_star=params["R0_val"],
        offdiag_R=offdiag_R,
        gamma=params["gamma"],
    )
    return beta_matrices, offdiag_R, False


def _export_parameters_csv(
    args: argparse.Namespace,
    df_sampled: pd.DataFrame,
    params: Dict,
    beta_matrices: List[np.ndarray],
    offdiag_R: Optional[np.ndarray],
) -> None:
    """Build and write the parameters CSV summarising the simulation setup."""
    ndemes = args.ndemes
    change_times = params["change_times"]
    R0_val = params["R0_val"]
    gamma_val = params["gamma"]
    population_sizes = params["population_sizes"]

    # Per-deme reproduction numbers R_j (column sums of next-generation matrix)
    f = population_sizes / population_sizes.sum()
    gamma_arr = np.full(ndemes, gamma_val)
    R_per_deme = [
        (bm @ np.diag(f) @ np.diag(1.0 / gamma_arr)).sum(axis=0)
        for bm in beta_matrices
    ]

    rows: List[Dict] = []

    # Per-deme scalar parameters
    for d in range(ndemes):
        demestr = str(d)
        rows.append(
            {"parameter": "gamma", "deme": demestr, "value": float(gamma_val)}
        )
        rows.append(
            {
                "parameter": "population_size",
                "deme": demestr,
                "value": float(population_sizes[d]),
            }
        )
        rows.append(
            {
                "parameter": "sampling_rate",
                "deme": demestr,
                "value": float(params["samplingrate"]),
            }
        )
        if offdiag_R is not None:
            for d2 in range(ndemes):
                if d != d2:
                    rows.append(
                        {
                            "parameter": "offdiag_R",
                            "deme": f"{d}_{d2}",
                            "value": float(offdiag_R[d][d2]),
                        }
                    )

    # Time-varying R* and per-deme R
    for i, bm in enumerate(beta_matrices):
        time = 0 if i == 0 else change_times[i - 1]
        for d in range(ndemes):
            rows.append(
                {
                    "parameter": f"Rstar_{time}",
                    "deme": str(d),
                    "value": float(R0_val[i]),
                }
            )
            rows.append(
                {
                    "parameter": f"R_{time}",
                    "deme": str(d),
                    "value": float(R_per_deme[i][d]),
                }
            )

    # Beta entries (N-scaled and raw)
    for step, bm in enumerate(beta_matrices):
        time = 0 if step == 0 else change_times[step - 1]
        for i in range(ndemes):
            for j in range(ndemes):
                rows.append(
                    {
                        "parameter": f"beta_{time}_Nscaled",
                        "deme": f"{i}->{j}",
                        "value": float(bm[i, j] / population_sizes[j]),
                    }
                )
    for step, bm in enumerate(beta_matrices):
        time = 0 if step == 0 else change_times[step - 1]
        for i in range(ndemes):
            for j in range(ndemes):
                rows.append(
                    {
                        "parameter": f"beta_{time}",
                        "deme": f"{i}->{j}",
                        "value": float(bm[i, j]),
                    }
                )

    # Datastream parameters (pass through from sampled params)
    ds_params = df_sampled[df_sampled["parameter"].str.startswith("ds_")]
    for _, row in ds_params.iterrows():
        rows.append(
            {"parameter": row["parameter"], "deme": row["deme"], "value": row["value"]}
        )

    df_params = pd.DataFrame(rows, columns=["parameter", "deme", "value"])
    if args.params_csv is not None:
        csv_path = args.params_csv
    else:
        base, _ = os.path.splitext(args.output_file)
        csv_path = f"{base}_parameters.csv"
    df_params.to_csv(csv_path, index=False)
    print(f"Wrote parameters CSV to: {csv_path}")


def main() -> None:
    """Orchestrate BEAST2 XML generation for stochastic SIR simulations."""
    args = parse_arguments()

    # 1. Load and validate inputs
    df_sampled, params = load_inputs(args)

    # 2. Compute transmission-rate matrices
    beta_matrices, offdiag_R, time_varying_interdeme_R0 = compute_betas(
        args, df_sampled, params
    )

    # 3. Build reactions
    reactions = create_transmission_reactions(
        beta_matrices=beta_matrices,
        change_times=params["change_times"],
        population_sizes=params["population_sizes"],
        gamma=params["gamma"],
        sampling_rate=params["samplingrate"],
        time_varying_interdeme_R0=time_varying_interdeme_R0,
    )

    # 4. Export parameters CSV
    _export_parameters_csv(args, df_sampled, params, beta_matrices, offdiag_R)

    # 5. Set up population states and generate XML
    ndemes = args.ndemes
    zero_str = " ".join(["0"] * ndemes)
    populations = {
        "S": ("population", " ".join(map(str, params["S_list"]))),
        "I": ("population", " ".join(map(str, params["I_list"]))),
        "Rh": ("population", zero_str),
        "sample": ("samplePopulation", zero_str),
        "NewInfectCount": ("population", zero_str),
    }

    freq_parameter = [float(x) for x in args.freqParameter.strip().split()]
    if len(freq_parameter) != 4:
        raise ValueError("Must provide exactly 4 base frequencies")
    if not np.isclose(sum(freq_parameter), 1.0):
        print("Warning: Base frequencies do not sum to 1.0")

    create_birthdeath_xml(
        output_file=args.output_file,
        reactions=reactions,
        populations=populations,
        mutation_rate=params["mutation_rate"],
        nsims=args.nsims,
        kappa=args.kappa,
        freq_parameter=freq_parameter,
        maxTime=args.maxTime,
        endsWhen=args.endsWhen,
    )
    print(f"Successfully created BEAST2 XML file: {args.output_file}")


if __name__ == "__main__":
    main()
